"""log.md: the generated, human-readable change log (MEMORY_FORMAT.md §4.2)."""

import json
from datetime import UTC, datetime, timedelta

from openmymemo.connectors import Connectors
from openmymemo.context import LOG_LIMIT, render_log_md
from openmymemo.proposals import Proposals


def entries(vault) -> list[str]:
    return [line for line in vault.log_md_path.read_text(encoding="utf-8").splitlines() if line.startswith("- ")]


def test_log_is_written_with_the_vault_and_on_every_change(vault):
    text = vault.log_md_path.read_text(encoding="utf-8")
    assert text.startswith("<!-- Generated by OpenMyMemo") and "_Nothing has changed yet._" in text

    m = vault.add("work", "Works on the iOS app")
    today = datetime.now(UTC).astimezone().date().isoformat()
    text = vault.log_md_path.read_text(encoding="utf-8")
    assert f"\n## {today}\n" in text
    assert entries(vault) == [f'- **You** added to Work: "Works on the iOS app" (^{m.id})']

    vault.update(m.id, content="Leads the iOS team")
    vault.update(m.id, topic="projects")
    vault.archive(m.id)
    vault.restore(m.id)
    assert entries(vault) == [
        f'- **You** restored to Projects: "Leads the iOS team" (^{m.id})',
        f'- **You** archived from Projects: "Leads the iOS team" (^{m.id})',
        f'- **You** moved "Leads the iOS team" from Work to Projects (^{m.id})',
        f'- **You** edited Work: "Works on the iOS app" → "Leads the iOS team" (^{m.id})',
        f'- **You** added to Work: "Works on the iOS app" (^{m.id})',
    ]


def test_log_names_apps_imports_editors_and_undo(vault):
    cons = Connectors(vault)
    claude = cons.ensure("claude-desktop", "Claude Desktop")
    props = Proposals(vault)
    imported = vault.add("tools", "Uses Homebrew", source="import:chatgpt", actor="import:chatgpt")
    pid = props.propose(claude, "add", content="Drinks oolong tea every afternoon", topic="lifestyle")["proposal_id"]
    tea = props.get(pid).applied_memory_id
    upd = props.propose(claude, "update", memory_id=tea, content="Drinks green tea every afternoon")["proposal_id"]
    path = vault.memories_dir / "tools.md"
    path.write_text(path.read_text(encoding="utf-8").replace("Uses Homebrew", "Uses Homebrew and MacPorts"),
                    encoding="utf-8")
    vault._sig = None  # the editor's change is noticed on the next sync
    vault.sync()
    props.undo(upd)
    cat = props.propose(claude, "add", content="Owns a cat named Mochi", topic="people")["proposal_id"]
    props.undo(cat)
    mochi = props.get(cat).applied_memory_id

    assert entries(vault) == [
        f"- **You** undid Claude Desktop's change to People (^{mochi})",
        f'- **Claude Desktop** added to People: "Owns a cat named Mochi" (^{mochi})',
        f"- **You** undid Claude Desktop's change to Lifestyle (^{tea})",
        f'- **You (in an editor)** edited Tools and setup: "Uses Homebrew" → "Uses Homebrew and MacPorts" '
        f"(^{imported.id})",
        f'- **Claude Desktop** edited Lifestyle: "Drinks oolong tea every afternoon" → '
        f'"Drinks green tea every afternoon" (^{tea})',
        f'- **Claude Desktop** added to Lifestyle: "Drinks oolong tea every afternoon" (^{tea})',
        f'- **Import from ChatGPT** added to Tools and setup: "Uses Homebrew" (^{imported.id})',
    ]
    assert props.get(upd).status == props.get(cat).status == "undone" and props.get(pid).status == "applied"


def test_accepting_is_not_an_undo_and_private_text_stays_out(vault):
    cons = Connectors(vault)
    claude = cons.ensure("claude-desktop", "Claude Desktop")
    props = Proposals(vault)
    pid = props.propose(claude, "add", content="Allergic to peanuts", topic="health")["proposal_id"]
    props.accept(pid)
    accepted = props.get(pid)
    props.undo(pid)
    assert entries(vault) == [
        f"- **You** undid Claude Desktop's change to Health (^{accepted.applied_memory_id})",
        f"- **You** added a private memory to Health (^{accepted.applied_memory_id})",
    ]
    assert "peanuts" not in vault.log_md_path.read_text(encoding="utf-8")


def test_days_are_newest_first_and_the_log_is_capped(vault):
    rows = []
    start = datetime(2026, 1, 1, 12, tzinfo=UTC)
    for i in range(LOG_LIMIT + 5):
        rows.append({"at": (start + timedelta(hours=i)).isoformat(), "memory_id": f"m{i:04d}", "version": 1,
                     "op": "create", "content": f"Memory {i}", "topic": "work", "actor": "user"})
    with open(vault.history_path, "w", encoding="utf-8") as fh:
        fh.writelines(json.dumps(r) + "\n" for r in rows)
    text = render_log_md(vault)
    lines = [line for line in text.splitlines() if line.startswith("- ")]
    assert len(lines) == LOG_LIMIT
    assert lines[0] == '- **You** added to Work: "Memory 504" (^m0504)'
    assert lines[-1] == '- **You** added to Work: "Memory 5" (^m0005)'
    days = [line[3:] for line in text.splitlines() if line.startswith("## ")]
    assert days == sorted(days, reverse=True) and len(days) == len(set(days))
    assert text.rstrip().endswith("_5 older entries are in .openmymemo/history.jsonl._")


def test_log_is_not_rewritten_when_nothing_changed(vault):
    vault.add("work", "Works on the iOS app")
    before = vault.log_md_path.stat().st_mtime_ns
    vault._render_log_md()
    vault.update_topic("work", description="Job and colleagues")  # renders, but the log reads the same
    assert vault.log_md_path.stat().st_mtime_ns == before
    vault.log_md_path.unlink()
    vault._sig = None
    vault.sync()  # a missing log.md is written again
    assert "Works on the iOS app" in vault.log_md_path.read_text(encoding="utf-8")
